"""File-management helpers: atomic writes, backups, managed blocks, logging."""

from __future__ import annotations

import hashlib
import logging
import os
import re
import shutil
from pathlib import Path

MARKER = "kde-material-you-colors hook"
BACKUP_DIR = Path(__file__).resolve().parent / "backups"

_DRY_RUN = False


def set_dry_run(enabled: bool) -> None:
    """When enabled, every write/backup below becomes a no-op."""
    global _DRY_RUN
    _DRY_RUN = enabled


def log() -> logging.Logger:
    return logging.getLogger("kmy-hook")


def _ensure_parent(path: Path) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)


def file_hash(path: Path) -> str:
    try:
        return hashlib.sha256(path.read_bytes()).hexdigest()[:16]
    except OSError:
        return ""


def backup_once(path: Path) -> None:
    """Keep the first-touch copy of a user file we are about to manage."""
    if _DRY_RUN:
        return
    if not path.exists():
        return
    dest = BACKUP_DIR / str(path).lstrip("/")
    if dest.exists():
        return
    try:
        if MARKER in path.read_text(encoding="utf-8", errors="replace"):
            return  # already generated by the hook; nothing user-authored to keep
    except OSError:
        pass
    _ensure_parent(dest)
    shutil.copy2(path, dest)
    log().info("backup: %s -> %s", path, dest)


def atomic_write(path: Path, content: str, mode: int | None = None) -> None:
    if _DRY_RUN:
        log().info("dry-run: not writing %s", path)
        return
    _ensure_parent(path)
    tmp = path.with_name(path.name + f".tmp{os.getpid()}")
    tmp.write_text(content, encoding="utf-8")
    if mode is not None:
        os.chmod(tmp, mode)
    elif path.exists():
        os.chmod(tmp, path.stat().st_mode & 0o7777)
    os.replace(tmp, path)


def write_if_changed(path: Path, content: str) -> bool:
    """Write ``content`` only when different. Returns True when the file changed."""
    if path.exists():
        try:
            if path.read_text(encoding="utf-8") == content:
                return False
        except OSError:
            pass
    atomic_write(path, content)
    return True


def set_arg_line(path: Path, arg: str, value: str) -> bool:
    """Ensure a single ``--arg="value"`` line (bat-style config files)."""
    backup_once(path)
    lines = path.read_text(encoding="utf-8").splitlines() if path.exists() else []
    wanted = f'{arg}="{value}"'
    pattern = re.compile(rf"^\s*{re.escape(arg)}\s*[= ]")
    matches = [i for i, line in enumerate(lines) if pattern.match(line)]
    if matches:
        if lines[matches[0]].strip() == wanted and len(matches) == 1:
            return False
        lines[matches[0]] = wanted
        for idx in reversed(matches[1:]):
            del lines[idx]
        atomic_write(path, "\n".join(lines) + "\n")
        return True
    lines.append(wanted)
    atomic_write(path, "\n".join(lines) + "\n")
    return True


def set_key_line(path: Path, key: str, value: str, header: str | None = None) -> bool:
    """Ensure ``key = value`` appears exactly once (replacing an existing key line).

    ``header`` (INI/TOML section) is kept inside the header block if given.
    Returns True when the file changed.
    """
    backup_once(path)
    lines = path.read_text(encoding="utf-8").splitlines() if path.exists() else []
    pattern = re.compile(rf"^\s*{re.escape(key)}\s*[:=]")
    matches = [i for i, line in enumerate(lines) if pattern.match(line)]

    if matches:
        changed = False
        for idx in reversed(matches[1:]):
            del lines[idx]
            changed = True
        idx = matches[0]
        if lines[idx].strip() != f"{key} = {value}":
            lines[idx] = f"{key} = {value}"
            changed = True
        if changed:
            atomic_write(path, "\n".join(lines) + "\n")
        return changed

    # Not present: insert after the header block (or append).
    insert_at = len(lines)
    if header:
        hdr = re.compile(rf"^\s*\[{re.escape(header)}\]\s*$")
        for i, line in enumerate(lines):
            if hdr.match(line):
                insert_at = i + 1
                break
    lines.insert(insert_at, f"{key} = {value}")
    atomic_write(path, "\n".join(lines) + "\n")
    return True


def rotate_log(path: Path, limit: int = 256 * 1024) -> None:
    try:
        if path.exists() and path.stat().st_size > limit:
            path.replace(path.with_suffix(path.suffix + ".1"))
    except OSError:
        pass

