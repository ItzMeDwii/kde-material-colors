"""Ghostty: generated theme + `theme = MaterialYou` in config.ghostty."""

from __future__ import annotations

import os
import shutil
import signal
import subprocess
from pathlib import Path

import managed

NAME = "ghostty"
THEME_NAME = "MaterialYou"


def _config_dir() -> Path:
    base = os.environ.get("XDG_CONFIG_HOME") or str(Path.home() / ".config")
    return Path(base) / "ghostty"


def _theme_path() -> Path:
    return _config_dir() / "themes" / THEME_NAME


def available(_ctx) -> bool:
    return shutil.which("ghostty") is not None


def _theme_file(ctx) -> str:
    p = ctx.palette
    lines = [
        f"# Generated by the {managed.MARKER} (Material You {p.variant})",
        f"background = {p.bg}",
        f"foreground = {p.fg}",
        f"cursor-color = {p.cursor}",
        f"cursor-text = {p.cursor_text}",
        f"selection-background = {p.selection_bg}",
        f"selection-foreground = {p.selection_fg}",
    ]
    lines += [f"palette = {i}={color}" for i, color in enumerate(p.ansi)]
    return "\n".join(lines) + "\n"


def apply(ctx) -> None:
    ctx.write(_theme_path(), _theme_file(ctx))
    config = _config_dir() / "config.ghostty"
    managed.set_key_line(config, "theme", THEME_NAME)
    ctx.changed[str(config)] = True
    ctx.track(config)


def reload(ctx) -> None:
    if not ctx.changed.get(str(_theme_path())) and not ctx.changed.get(
        str(_config_dir() / "config.ghostty")
    ):
        return
    # Ghostty reloads its configuration on SIGUSR2 (same signal its
    # systemd `notify-reload` unit uses).
    try:
        pids = subprocess.run(
            ["pgrep", "-x", "ghostty"], capture_output=True, text=True, check=False
        ).stdout.split()
        for pid in pids:
            os.kill(int(pid), signal.SIGUSR2)
        if pids:
            managed.log().info("ghostty: reloaded (%s pid(s))", len(pids))
    except (OSError, ValueError) as exc:
        managed.log().warning("ghostty: reload failed: %s", exc)
