def _ensure_import(gtk_css: Path, name: str) -> bool:
    import_line = f"@import '{name}';"
    text = gtk_css.read_text(encoding="utf-8") if gtk_css.exists() else ""
    lines = text.splitlines()
    if import_line in lines:
        return False
    return managed.write_if_changed(gtk_css, (text.rstrip("\n") + "\n" if text else "") + import_line + "\n")


def _apply_gsettings(ctx) -> None:
    p = ctx.palette
    accent = nearest_hue(p.role("primary"), NAMED_ACCENTS)
    scheme = "prefer-dark" if p.is_dark else "prefer-light"
    if ctx.dry_run:
        managed.log().info("dry-run: gsettings accent-color=%s color-scheme=%s", accent, scheme)
        return
    for key, value in (("accent-color", accent), ("color-scheme", scheme)):
        try:
            result = subprocess.run(
                ["gsettings", "set", "org.gnome.desktop.interface", key, value],
                capture_output=True,
                text=True,
                check=False,
                timeout=10,
            )
            if result.returncode != 0:
                managed.log().warning("gsettings %s failed: %s", key, result.stderr.strip())
        except (OSError, subprocess.TimeoutExpired) as exc:
            managed.log().warning("gsettings %s failed: %s", key, exc)


def apply(ctx) -> None:
    css = _css(ctx)
    for version in ("gtk-3.0", "gtk-4.0"):
        directory = _config_root() / version
        ctx.write(directory / "material-you.css", css)
        gtk_css = directory / "gtk.css"
        if ctx.dry_run:
            managed.log().info("dry-run: would ensure imports in %s", gtk_css)
            continue
        changed = _ensure_import(gtk_css, "colors.css")
        changed = _ensure_import(gtk_css, "material-you.css") or changed
        if changed:
            ctx.changed[str(gtk_css)] = True
        ctx.track(gtk_css)
    _apply_gsettings(ctx)
