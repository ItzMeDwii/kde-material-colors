"""nvim: generated lua colorscheme + the LazyVim spec that selects it."""

from __future__ import annotations

import shutil
from pathlib import Path

import managed
from .vim import GROUPS, _resolve  # same palette tokens as the vim theme

NAME = "nvim"

# Neovim-only groups layered on top of the shared vim set.
NVIM_GROUPS: list[tuple[str, str | None, str | None, str]] = [
    ("NormalFloat", "fg", "surfaceContainer", ""),
    ("FloatBorder", "outline", "surfaceContainer", ""),
    ("FloatTitle", "primary", "surfaceContainer", "bold"),
    ("WinSeparator", "outline", "bg", ""),
    ("DiagnosticError", "error", None, ""),
    ("DiagnosticWarn", "number", None, ""),
    ("DiagnosticInfo", "tertiaryFixedDim", None, ""),
    ("DiagnosticHint", "preproc", None, ""),
    ("DiagnosticOk", "primary", None, ""),
]

# Treesitter captures with explicit colours (the runtime leaves these empty,
# so they would otherwise render unstyled).
TS_GROUPS: list[tuple[str, str | None, str | None, str]] = [
    ("@variable.builtin", "fg", None, "italic"),
    ("@variable.parameter", "fg", None, "italic"),
    ("@variable.member", "onSurfaceVariant", None, ""),
    ("@property", "onSurfaceVariant", None, ""),
    ("@tag.attribute", "onSurfaceVariant", None, ""),
    ("@function.builtin", "primary", None, "italic"),
    ("@string.regexp", "number", None, ""),
]

# (group, target): unstyled runtime captures routed to a base group, plus the
# LSP semantic-token groups that need a non-default route. Every other
# @lsp.type.* inherits through its default chain (@lsp.type.X -> @X -> base).
LINKS: list[tuple[str, str]] = [
    # treesitter
    ("@function.call", "Function"),
    ("@function.method", "Function"),
    ("@function.method.call", "Function"),
    ("@function.macro", "Macro"),
    ("@type.definition", "Type"),
    ("@constant.macro", "Macro"),
    ("@type.qualifier", "Keyword"),
    ("@keyword.function", "Keyword"),
    ("@keyword.return", "Keyword"),
    ("@keyword.operator", "Keyword"),
    ("@keyword.conditional", "Conditional"),
    ("@keyword.repeat", "Repeat"),
    ("@keyword.exception", "Exception"),
    ("@keyword.directive", "PreProc"),
    ("@keyword.import", "Include"),
    ("@exception", "Exception"),
    ("@punctuation.bracket", "Delimiter"),
    ("@punctuation.delimiter", "Delimiter"),
    ("@comment.documentation", "Comment"),
    ("@namespace", "Structure"),
    ("@tag.delimiter", "Delimiter"),
    ("@field", "@variable.member"),
    # LSP semantic tokens
    ("@lsp.typemod.variable.readonly", "Constant"),
    ("@lsp.typemod.variable.defaultLibrary", "@variable.builtin"),
    ("@lsp.typemod.function.defaultLibrary", "@function.builtin"),
]

# (group, sp token, attrs): undercurl colour comes from `sp`, not fg.
UNDERCURL_GROUPS: list[tuple[str, str, str]] = [
    ("DiagnosticUnderlineError", "error", "undercurl"),
    ("DiagnosticUnderlineWarn", "number", "undercurl"),
    ("DiagnosticUnderlineInfo", "tertiaryFixedDim", "undercurl"),
    ("DiagnosticUnderlineHint", "preproc", "undercurl"),
    ("DiagnosticUnderlineOk", "primary", "undercurl"),
]


def _dir() -> Path:
    return Path.home() / ".config" / "nvim"


def available(_ctx) -> bool:
    return shutil.which("nvim") is not None


def _table(parts: list[str]) -> str:
    return "{ " + ", ".join(parts) + " }"


def _colorscheme(ctx) -> str:
    p = ctx.palette
    lines = [
        f"-- Generated by the {managed.MARKER} (Material You {p.variant})",
        'vim.cmd("hi clear")',
        'if vim.fn.exists("syntax_on") == 1 then',
        '  vim.cmd("syntax reset")',
        "end",
        'vim.g.colors_name = "material-you"',
        f'vim.o.background = "{"dark" if p.is_dark else "light"}"',
        "",
        "local hi = vim.api.nvim_set_hl",
        "",
    ]
    for group, fg_tok, bg_tok, attrs in GROUPS + NVIM_GROUPS + TS_GROUPS:
        parts: list[str] = []
        if fg_tok:
            color, cterm = _resolve(ctx, fg_tok)
            parts.append(f'fg = "{color}", ctermfg = {cterm}')
        if bg_tok:
            color, cterm = _resolve(ctx, bg_tok)
            parts.append(f'bg = "{color}", ctermbg = {cterm}')
        parts.extend(f"{attr} = true" for attr in attrs.split())
        lines.append(f'hi(0, "{group}", {_table(parts)})')
    lines.append("")
    for group, target in LINKS:
        lines.append(f'hi(0, "{group}", {{ link = "{target}" }})')
    lines.append("")
    for group, sp_tok, attrs in UNDERCURL_GROUPS:
        color, _cterm = _resolve(ctx, sp_tok)
        parts = [f'sp = "{color}"']
        parts.extend(f"{attr} = true" for attr in attrs.split())
        lines.append(f'hi(0, "{group}", {_table(parts)})')
    return "\n".join(lines) + "\n"


def _spec(ctx) -> str:
    return (
        f"-- Generated by the {managed.MARKER} (Material You {ctx.palette.variant})\n"
        "-- Select the generated colors/material-you.lua in LazyVim.\n"
        "-- Re-run the hook after a palette change, then restart nvim (or :colorscheme material-you).\n"
        "return {\n"
        "  {\n"
        '    "LazyVim/LazyVim",\n'
        "    opts = {\n"
        '      colorscheme = "material-you",\n'
        "    },\n"
        "  },\n"
        "}\n"
    )


def apply(ctx) -> None:
    root = _dir()
    ctx.write(root / "colors" / "material-you.lua", _colorscheme(ctx))
    ctx.write(root / "lua" / "plugins" / "material-you.lua", _spec(ctx))
