"""btop: generated theme + `color_theme` in btop.conf."""

from __future__ import annotations

import os
import shutil

import subprocess
from pathlib import Path

import managed

NAME = "btop"


def _dir() -> Path:
    base = os.environ.get("XDG_CONFIG_HOME") or str(Path.home() / ".config")
    return Path(base) / "btop"


def available(_ctx) -> bool:
    return shutil.which("btop") is not None


def _theme_file(ctx) -> str:
    p = ctx.palette
    green = p.ansi_named("green")
    yellow = p.ansi_named("yellow")
    red = p.ansi_named("red")
    outline = p.role("outline")
    values = {
        "main_bg": p.bg,
        "main_fg": p.fg,
        "title": p.role("primary"),
        "hi_fg": p.role("secondary"),
        "selected_bg": p.role("surfaceVariant"),
        "selected_fg": p.selection_fg,
        "inactive_fg": outline,
        "proc_misc": p.role("tertiary"),
        "cpu_box": outline,
        "mem_box": outline,
        "net_box": outline,
        "proc_box": outline,
        "div_line": p.role("outlineVariant"),
        "temp_start": green,
        "temp_mid": yellow,
        "temp_end": red,
        "cpu_start": green,
        "cpu_mid": yellow,
        "cpu_end": red,
        "free_start": green,
        "free_mid": yellow,
        "free_end": red,
        "cached_start": green,
        "cached_mid": yellow,
        "cached_end": red,
        "available_start": green,
        "available_mid": yellow,
        "available_end": red,
        "used_start": green,
        "used_mid": yellow,
        "used_end": red,
        "download_start": green,
        "download_mid": yellow,
        "download_end": red,
        "upload_start": green,
        "upload_mid": yellow,
        "upload_end": red,
    }
    lines = [
        f"# Generated by the {managed.MARKER} (Material You {p.variant})",
        "",
    ]
    lines += [f'theme[{key}]="{value}"' for key, value in values.items()]
    return "\n".join(lines) + "\n"


def apply(ctx) -> None:
    ctx.write(_dir() / "themes" / "material-you.theme", _theme_file(ctx))
    conf = _dir() / "btop.conf"
    managed.set_key_line(conf, "color_theme", '"material-you"')
    ctx.changed[str(conf)] = True
    ctx.track(conf)


def reload(ctx) -> None:
    if not ctx.any_changed():
        return
    try:
        result = subprocess.run(
            ["pkill", "-SIGUSR2", "-x", "btop"], capture_output=True, text=True, check=False
        )
        if result.returncode == 0:
            managed.log().info("btop: reloaded running instances")
    except OSError as exc:
        managed.log().warning("btop: reload failed: %s", exc)
