"""Alacritty: imported colors file + managed `import` in alacritty.toml.

Alacritty loads the importing file *last*, so the user's own [colors] tables
would win. They are therefore migrated into the generated file on first run.
"""

from __future__ import annotations

import re
import shutil
from pathlib import Path

import managed

NAME = "alacritty"
THEME_FILE = "material-you.toml"

SECTION_RE = re.compile(r"^\s*\[([^\]]+)\]\s*$")
COLORS_SECTION_RE = re.compile(r"^colors(\..+)?$")
IMPORT_START_RE = re.compile(r"^\s*import\s*=")


def _dir() -> Path:
    return Path.home() / ".config" / "alacritty"


def available(_ctx) -> bool:
    return shutil.which("alacritty") is not None


def _theme_file(ctx) -> str:
    p = ctx.palette
    return f"""# Generated by the {managed.MARKER} (Material You {p.variant})
# Imported by alacritty.toml - do not edit by hand.

[colors.primary]
background = "{p.bg}"
foreground = "{p.fg}"

[colors.cursor]
text = "{p.cursor_text}"
cursor = "{p.cursor}"

[colors.selection]
text = "{p.selection_fg}"
background = "{p.selection_bg}"

[colors.normal]
black = "{p.ansi_named('black')}"
red = "{p.ansi_named('red')}"
green = "{p.ansi_named('green')}"
yellow = "{p.ansi_named('yellow')}"
blue = "{p.ansi_named('blue')}"
magenta = "{p.ansi_named('magenta')}"
cyan = "{p.ansi_named('cyan')}"
white = "{p.ansi_named('white')}"

[colors.bright]
black = "{p.ansi_named('br_black')}"
red = "{p.ansi_named('br_red')}"
green = "{p.ansi_named('br_green')}"
yellow = "{p.ansi_named('br_yellow')}"
blue = "{p.ansi_named('br_blue')}"
magenta = "{p.ansi_named('br_magenta')}"
cyan = "{p.ansi_named('br_cyan')}"
white = "{p.ansi_named('br_white')}"
"""


def _drop_colors_sections(text: str) -> str:
    """Remove every [colors] / [colors.*] table (headers + bodies)."""
    kept: list[str] = []
    dropping = False
    for line in text.splitlines():
        m = SECTION_RE.match(line)
        if m:
            dropping = bool(COLORS_SECTION_RE.match(m.group(1)))
        if not dropping:
            kept.append(line)
    return "\n".join(kept).rstrip("\n") + "\n"


def _rewrite_import(text: str) -> str | None:
    """Normalize the existing `import = ...` statement, or return None."""
    lines = text.splitlines()
    for i, line in enumerate(lines):
        if not IMPORT_START_RE.match(line):
            continue
        # Collect the statement span (arrays may span lines).
        depth = 0
        end = i
        for j in range(i, len(lines)):
            depth += lines[j].count("[") - lines[j].count("]")
            end = j
            if depth <= 0 and j >= i:
                break
        statement = "\n".join(lines[i : end + 1])
        entries = re.findall(r'"([^"]+)"', statement)
        entries = [THEME_FILE] + [e for e in entries if e != THEME_FILE]
        new_stmt = "import = [" + ", ".join(f'"{e}"' for e in entries) + "]"
        lines[i : end + 1] = [new_stmt]
        return "\n".join(lines) + "\n"
    return None


def _migrate(project: Path) -> bool:
    """Move [colors*] tables out of alacritty.toml; ensure the import exists."""
    original = project.read_text(encoding="utf-8")
    text = _drop_colors_sections(original)

    rewritten = _rewrite_import(text)
    if rewritten is not None:
        text = rewritten
    else:
        import_line = f'import = ["{THEME_FILE}"]'
        lines = text.splitlines()
        general_idx = None
        for i, line in enumerate(lines):
            m = SECTION_RE.match(line)
            if m and m.group(1) == "general":
                general_idx = i
                break
        if general_idx is not None:
            lines.insert(general_idx + 1, import_line)
            text = "\n".join(lines) + "\n"
        else:
            text = f"[general]\n{import_line}\n\n" + text

    if text == original:
        return False
    managed.backup_once(project)
    managed.atomic_write(project, text)
    managed.log().info("alacritty: migrated %s", project)
    return True


def apply(ctx) -> None:
    ctx.write(_dir() / THEME_FILE, _theme_file(ctx))
    project = _dir() / "alacritty.toml"
    if ctx.dry_run:
        managed.log().info("dry-run: would migrate %s and set decorations_theme_variant", project)
        return
    if project.exists() and _migrate(project):
        ctx.changed[str(project)] = True
    variant = "Dark" if ctx.palette.is_dark else "Light"
    if managed.set_key_line(project, "decorations_theme_variant", f'"{variant}"', header="window"):
        ctx.changed[str(project)] = True
    ctx.track(project)
