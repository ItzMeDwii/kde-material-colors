"""fish: colour variables, fzf colours and LS_COLORS via a conf.d snippet."""

from __future__ import annotations

import shutil
from pathlib import Path

import managed
from mycolors import parse_hex

NAME = "fish"


def _conf_dir() -> Path:
    base = Path.home() / ".config"
    return base / "fish" / "conf.d"


def available(_ctx) -> bool:
    return shutil.which("fish") is not None


def _tc(hex_color: str) -> str:
    r, g, b = parse_hex(hex_color)
    return f"38;2;{r};{g};{b}"


def _fzf_colors(ctx) -> str:
    p = ctx.palette
    return ",".join(
        [
            f"fg:{p.fg}",
            f"bg:{p.bg}",
            f"hl:{p.role('primary')}",
            f"fg+:{p.fg}",
            f"bg+:{p.role('surfaceVariant')}",
            f"hl+:{p.role('primary')}",
            f"info:{p.role('secondary')}",
            f"border:{p.role('outline')}",
            f"prompt:{p.role('primary')}",
            f"pointer:{p.role('tertiary')}",
            f"marker:{p.ansi_named('cyan')}",
            f"spinner:{p.role('secondary')}",
            f"header:{p.ansi_named('yellow')}",
        ]
    )


def _ls_colors(ctx) -> str:
    p = ctx.palette
    d = {
        "di": "1;" + _tc(p.role("primary")),
        "ln": _tc(p.ansi_named("cyan")),
        "mh": _tc(p.ansi_named("br_cyan")),
        "pi": _tc(p.ansi_named("yellow")),
        "so": _tc(p.ansi_named("magenta")),
        "do": _tc(p.ansi_named("magenta")),
        "bd": _tc(p.ansi_named("yellow")),
        "cd": _tc(p.ansi_named("yellow")),
        "or": _tc(p.role("error")),
        "mi": _tc(p.role("error")),
        "su": _tc(p.role("error")),
        "sg": _tc(p.role("error")),
        "ca": _tc(p.role("error")),
        "tw": _tc(p.role("primary")),
        "ow": _tc(p.role("primary")),
        "st": _tc(p.role("primary")),
        "ex": "1;" + _tc(p.ansi_named("green")),
        "fi": _tc(p.fg),
    }
    return ":".join(f"{k}={v}" for k, v in d.items())


def _fish_file(ctx) -> str:
    p = ctx.palette
    colors = {
        "fish_color_normal": p.fg,
        "fish_color_command": p.role("primary"),
        "fish_color_param": p.fg,
        "fish_color_comment": p.role("outline"),
        "fish_color_error": p.role("error"),
        "fish_color_quote": p.ansi_named("green"),
        "fish_color_redirection": p.ansi_named("magenta"),
        "fish_color_end": p.role("outline"),
        "fish_color_operator": p.role("secondary"),
        "fish_color_escape": p.ansi_named("cyan"),
        "fish_color_keyword": p.ansi_named("magenta"),
        "fish_color_autosuggestion": p.role("outline"),
        "fish_color_valid_path": p.ansi_named("green"),
        "fish_color_cwd": p.ansi_named("cyan"),
        "fish_color_cwd_root": p.role("error"),
        "fish_color_user": p.role("secondary"),
        "fish_color_host": p.ansi_named("green"),
        "fish_color_host_remote": p.ansi_named("yellow"),
        "fish_color_status": p.role("error"),
        "fish_color_cancel": "-r",
        "fish_color_history_current": "--bold",
        "fish_color_search_match": "--background=" + p.role("surfaceVariant"),
        "fish_color_selection": f"{p.selection_fg} --background={p.selection_bg}",
        "fish_pager_color_prefix": p.role("primary"),
        "fish_pager_color_completion": p.fg,
        "fish_pager_color_description": p.role("outline"),
        "fish_pager_color_selected_background": "-r",
    }
    lines = [
        f"# Generated by the {managed.MARKER} (Material You {p.variant}).",
        "# Re-run: python3 ~/.config/kde-material-you-colors/hook/apply.py --force",
        "",
    ]
    for key, value in colors.items():
        lines.append(f"set -g {key} '{value}'")
    lines += [
        "",
        f"set -gx FZF_DEFAULT_OPTS \"--color={_fzf_colors(ctx)}\"",
        f"set -gx LS_COLORS '{_ls_colors(ctx)}'",
        "",
    ]
    return "\n".join(lines)


def apply(ctx) -> None:
    ctx.write(_conf_dir() / "material-you.fish", _fish_file(ctx))


def reload(_ctx) -> None:
    # conf.d is read by every new fish; running shells keep their variables.
    managed.log().info("fish: colours apply to new shells")
