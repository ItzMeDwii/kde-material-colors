"""fastfetch: config.jsonc with M3 colours, preserving other user settings.

fastfetch has no default value for `modules`: a config file without that key
renders the logo and nothing else. When the hook creates the file it therefore
writes fastfetch's built-in default module set; afterwards only the colour keys
are refreshed, so other edits (modules, formats, …) are kept.
"""

from __future__ import annotations

import json
import shutil
from pathlib import Path

import managed

NAME = "fastfetch"

# fastfetch's built-in default modules (fastfetch --format json without a config).
DEFAULT_MODULES = [
    "title",
    "separator",
    "os",
    "host",
    "kernel",
    "uptime",
    "packages",
    "shell",
    "display",
    "de",
    "wm",
    "wmtheme",
    "theme",
    "icons",
    "font",
    "cursor",
    "terminal",
    "terminalfont",
    "cpu",
    "gpu",
    "memory",
    "swap",
    "disk",
    "localip",
    "battery",
    "poweradapter",
    "locale",
    "break",
    "colors",
]


def _dir() -> Path:
    return Path.home() / ".config" / "fastfetch"


def available(_ctx) -> bool:
    return shutil.which("fastfetch") is not None


def strip_jsonc(text: str) -> str:
    """Remove // and /* */ comments that are outside of strings."""
    out: list[str] = []
    i, n = 0, len(text)
    in_string = False
    while i < n:
        char = text[i]
        if in_string:
            out.append(char)
            if char == "\\" and i + 1 < n:
                out.append(text[i + 1])
                i += 2
                continue
            if char == '"':
                in_string = False
            i += 1
            continue
        if char == '"':
            in_string = True
            out.append(char)
            i += 1
            continue
        if char == "/" and i + 1 < n and text[i + 1] == "/":
            while i < n and text[i] != "\n":
                i += 1
            continue
        if char == "/" and i + 1 < n and text[i + 1] == "*":
            i += 2
            while i + 1 < n and not (text[i] == "*" and text[i + 1] == "/"):
                i += 1
            i += 2
            continue
        out.append(char)
        i += 1
    return "".join(out)


def _load_existing(config: Path) -> dict:
    if not config.exists():
        return {}
    try:
        data = json.loads(strip_jsonc(config.read_text(encoding="utf-8")))
        return data if isinstance(data, dict) else {}
    except ValueError as exc:
        managed.log().warning("fastfetch: cannot parse %s (%s); rewriting it", config, exc)
        return {}


def _config(ctx, data: dict) -> str:
    p = ctx.palette
    a = lambda name: p.ansi_named(name)  # noqa: E731

    data.setdefault("$schema", "https://github.com/fastfetch-cli/fastfetch/raw/dev/doc/json_schema.json")
    if not data.get("modules"):
        data["modules"] = DEFAULT_MODULES

    logo = data.setdefault("logo", {})
    logo["color"] = {
        "1": p.role("primary"),
        "2": p.role("tertiary"),
        "3": p.role("secondary"),
        "4": p.role("primaryFixedDim"),
        "5": p.role("secondaryFixedDim"),
        "6": p.role("error"),
        "7": p.role("outline"),
    }

    display = data.setdefault("display", {})
    display["color"] = {
        "keys": p.role("primary"),
        "title": p.role("primary"),
        "separator": p.role("outline"),
        "output": p.fg,
    }
    percent = display.setdefault("percent", {})
    percent["color"] = {"green": a("green"), "yellow": a("yellow"), "red": a("red")}

    return (
        f"// Generated by the {managed.MARKER} (Material You {p.variant})\n"
        + json.dumps(data, indent=4)
        + "\n"
    )


def apply(ctx) -> None:
    config = _dir() / "config.jsonc"
    if config.exists():
        text = config.read_text(encoding="utf-8")
        if managed.MARKER not in text:
            managed.log().info(
                "fastfetch: %s exists and is not hook-managed, leaving it alone", config
            )
            return
    ctx.write(config, _config(ctx, _load_existing(config)))
